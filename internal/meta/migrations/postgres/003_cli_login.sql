-- Device-flow logins for `doreg login`: the CLI asks for a code, the user
-- approves it in the browser, the CLI fetches a token once.
CREATE TABLE cli_devices (
	device_code_hash TEXT PRIMARY KEY,
	user_code        TEXT NOT NULL UNIQUE,
	client           TEXT NOT NULL DEFAULT '',
	created_at       BIGINT NOT NULL,
	expires_at       BIGINT NOT NULL,
	status           TEXT NOT NULL DEFAULT 'pending',
	user_id          BIGINT REFERENCES users(id) ON DELETE CASCADE,
	-- Held only between approval and the CLI's next poll, then the row is deleted.
	token            TEXT NOT NULL DEFAULT ''
);

-- Long-lived registry credentials issued to `doreg login`. Tokens are random,
-- so a SHA-256 lookup is safe and avoids bcrypt on every registry request.
CREATE TABLE cli_tokens (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name         TEXT NOT NULL,
	token_hash   TEXT NOT NULL UNIQUE,
	created_at   BIGINT NOT NULL,
	expires_at   BIGINT NOT NULL,
	last_used_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX cli_tokens_user ON cli_tokens(user_id);
